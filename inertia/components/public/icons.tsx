/** Ícono según el nombre de la red (fallback: globo). */
export function IconoRed({ nombre, size = 20 }: { nombre: string; size?: number }) {
  const n = nombre.toLowerCase()
  if (n.includes('facebook')) return <IconoFacebook size={size} />
  if (n.includes('instagram')) return <IconoInstagram size={size} />
  if (n.includes('youtube')) return <IconoYoutube size={size} />
  if (n.includes('whatsapp')) return <IconoWhatsApp size={size} />
  return <Globe size={size} />
}
